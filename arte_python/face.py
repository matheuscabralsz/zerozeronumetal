def load(art,pal=PAL):
    rows=art.strip('\n').split('\n');w=max(map(len,rows));h=len(rows)
    im=Image.new('RGBA',(w,h),(0,0,0,0))
    for y,r in enumerate(rows):
        for x,c in enumerate(r.ljust(w,'.')):
            v=pal.get(c)
            if v:im.putpixel((x,y),v+(255,))
    return im
